import { readFile } from "node:fs/promises";
import { HttpError, route } from "@/lib/api";
import { getProject } from "@/lib/db/projects";
import { assertSafeId, fromDataRelative } from "@/lib/security/paths";

export const dynamic = "force-dynamic";

type Ctx = { params: Promise<{ id: string }> };

/** The wordmark as SVG (default) or PNG. ?download=1 sends it as an attachment. */
export const GET = route<Ctx>(async (req, { params }) => {
  const { id } = await params;
  assertSafeId(id);
  const kit = (await getProject(id)).brandKit;
  if (!kit?.logoSvg) throw new HttpError(404, "No logo yet. Generate the brand kit first.");
  const url = new URL(req.url);
  const format = url.searchParams.get("format") === "png" ? "png" : "svg";
  const slug =
    (kit.selectedName ?? "logo")
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, "-")
      .replace(/^-|-$/g, "") || "logo";
  const disposition = url.searchParams.get("download")
    ? `attachment; filename="${slug}-logo.${format}"`
    : "inline";
  if (format === "png") {
    if (!kit.logoPngPath) throw new HttpError(404, "No PNG logo yet.");
    const data = await readFile(fromDataRelative(kit.logoPngPath));
    return new Response(new Uint8Array(data), {
      headers: {
        "Content-Type": "image/png",
        "Cache-Control": "private, no-cache",
        "Content-Disposition": disposition,
      },
    });
  }
  return new Response(kit.logoSvg, {
    headers: {
      "Content-Type": "image/svg+xml; charset=utf-8",
      "Cache-Control": "private, no-cache",
      "Content-Disposition": disposition,
      // The SVG is generated by us, but never let it run script if opened directly.
      "Content-Security-Policy": "default-src 'none'; style-src 'unsafe-inline'",
    },
  });
});
